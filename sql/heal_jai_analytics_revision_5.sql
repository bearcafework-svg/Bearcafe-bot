-- 1. Table: heal_jai_analytics_events
-- Purpose: Structured append-only audit and analytics stream for customer funnel,
-- operations, and resource lifecycle.
CREATE TABLE IF NOT EXISTS heal_jai_analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  idempotency_key TEXT UNIQUE NOT NULL,
  event_name TEXT NOT NULL,
  event_category TEXT NOT NULL CHECK (event_category IN ('TICKET', 'PAYMENT', 'DISPATCH', 'SESSION', 'STAFF', 'CLEANUP', 'SYSTEM')),
  status TEXT NOT NULL DEFAULT 'SUCCESS' CHECK (status IN ('SUCCESS', 'PARTIAL_SUCCESS', 'FAILURE')),
  ticket_id BIGINT REFERENCES heal_jai_tickets(id) ON DELETE SET NULL,
  order_id BIGINT REFERENCES heal_jai_orders_sessions(id) ON DELETE SET NULL,
  actor_id TEXT,
  guild_id TEXT,
  order_code TEXT,
  metadata JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_hj_analytics_name_created ON heal_jai_analytics_events(event_name, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_hj_analytics_idempotency ON heal_jai_analytics_events(idempotency_key);
CREATE INDEX IF NOT EXISTS idx_hj_analytics_order_id ON heal_jai_analytics_events(order_id);
CREATE INDEX IF NOT EXISTS idx_hj_analytics_category ON heal_jai_analytics_events(event_category);

ALTER TABLE heal_jai_analytics_events ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'heal_jai_analytics_events' AND policyname = 'Service role full access on heal_jai_analytics_events'
  ) THEN
    CREATE POLICY "Service role full access on heal_jai_analytics_events" ON heal_jai_analytics_events
      FOR ALL TO service_role USING (true) WITH CHECK (true);
  END IF;
END $$;


