/**
 * สุ่ม Anomaly ตาม Round และ Configuration
 * @param {number} round - รอบปัจจุบัน (1-5)
 * @param {number} anomalyLevel - ระดับความผิดปกติ (1-3)
 */
function rollAnomaly(round = 1, anomalyLevel = 1) {
  // โอกาสเกิด Anomaly ตามรอบ (Dynamic rate)
  const baseChances = {
    1: 0.15,
    2: 0.25,
    3: 0.35,
    4: 0.45,
    5: 0.60
  };

  const chance = (baseChances[round] || 0.3) + (anomalyLevel - 1) * 0.1;
  const roll = Math.random();

  if (roll > chance) {
    return null; // NORMAL Customer
  }

  // กรองตาม Anomaly Level
  let pool = ANOMALY_TEMPLATES;
  if (anomalyLevel === 1) {
    pool = ANOMALY_TEMPLATES.filter((a) => a.tier === ANOMALY_TIERS.MINOR || a.tier === ANOMALY_TIERS.MAJOR);
  }

  const selected = pool[Math.floor(Math.random() * pool.length)];
  return { ...selected };
}

