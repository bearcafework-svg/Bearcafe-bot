CREATE TABLE IF NOT EXISTS minigame_active_sessions (
    channel_id TEXT PRIMARY KEY,
    game_id INT NOT NULL,
    current_question JSONB NOT NULL,
    message_id TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

