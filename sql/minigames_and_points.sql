-- 4. ตารางบันทึกการชนะมินิเกมของผู้ใช้ (สำหรับจัดอันดับ Leaderboard แบบ 30 วัน และ แบบทั้งหมด)
CREATE TABLE IF NOT EXISTS minigame_wins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_id TEXT NOT NULL,
    game_id INT NOT NULL,
    points_earned INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_minigame_wins_leaderboard ON minigame_wins (discord_id, created_at);
CREATE INDEX IF NOT EXISTS idx_minigame_wins_game ON minigame_wins (game_id);

